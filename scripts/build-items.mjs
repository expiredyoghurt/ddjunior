// content/items.json is the source of truth. The game loads it as a plain script so it works from a folder (file://).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const items = JSON.parse(readFileSync(join(root, 'content/items.json'), 'utf8'));
const out = '/* Generated by scripts/build-items.mjs from content/items.json. Do not edit. */\n' +
  'window.DDJ = window.DDJ || {};\nwindow.DDJ.items = ' + JSON.stringify(items) + ';\n';
writeFileSync(join(root, 'public/js/items-data.js'), out);
console.log('items-data.js written:', items.length, 'items');
